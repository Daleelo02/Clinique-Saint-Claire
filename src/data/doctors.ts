export function getDoctorById(id: string): Doctor | undefined {
  return doctors.find(d => d.id === id);
}

export function getDoctorsBySpecialty(specialtyId: string): Doctor[] {
  return doctors.filter(d => d.specialtyId === specialtyId);
}

export function searchDoctors(query: string): Doctor[] {
  const q = query.toLowerCase().trim();
  if (!q) return doctors;
  return doctors.filter(d =>
    `${d.firstName} ${d.lastName}`.toLowerCase().includes(q) ||
    d.specialty.toLowerCase().includes(q) ||
    d.specialtyId.toLowerCase().includes(q) ||
    d.languages.some(lang => lang.toLowerCase().includes(q))
  );
}